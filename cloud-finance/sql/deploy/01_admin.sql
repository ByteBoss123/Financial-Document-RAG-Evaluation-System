-- CloudLedger admin setup. Run once as ACCOUNTADMIN (role/warehouse/grant creation).
-- Everything else runs as CLOUDLEDGER_ROLE. MCP_ACCESS_ROLE is not widened.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS CLOUDLEDGER_ROLE COMMENT = 'CloudLedger pipeline and app owner';
CREATE ROLE IF NOT EXISTS CLOUDLEDGER_VIEWER COMMENT = 'CloudLedger read-only app viewers';
GRANT ROLE CLOUDLEDGER_VIEWER TO ROLE CLOUDLEDGER_ROLE;
GRANT ROLE CLOUDLEDGER_ROLE TO ROLE SYSADMIN;
GRANT ROLE CLOUDLEDGER_ROLE TO USER "amarnathreddyganta5";

-- Dedicated X-Small warehouse with a hard credit cap.
CREATE WAREHOUSE IF NOT EXISTS CLOUDLEDGER_WH
  WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE
  COMMENT = 'CloudLedger loads, refresh task and Streamlit queries';
CREATE RESOURCE MONITOR IF NOT EXISTS CLOUDLEDGER_RM WITH CREDIT_QUOTA = 5
  FREQUENCY = MONTHLY START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 80 PERCENT DO NOTIFY ON 100 PERCENT DO SUSPEND;
ALTER WAREHOUSE CLOUDLEDGER_WH SET RESOURCE_MONITOR = CLOUDLEDGER_RM;
GRANT USAGE, OPERATE ON WAREHOUSE CLOUDLEDGER_WH TO ROLE CLOUDLEDGER_ROLE;
GRANT USAGE ON WAREHOUSE CLOUDLEDGER_WH TO ROLE CLOUDLEDGER_VIEWER;

-- Project database: the project role may create schemas but does not own the database.
CREATE DATABASE IF NOT EXISTS CLOUDLEDGER COMMENT = 'CloudLedger cloud-finance BI';
GRANT USAGE, CREATE SCHEMA ON DATABASE CLOUDLEDGER TO ROLE CLOUDLEDGER_ROLE;
GRANT USAGE ON DATABASE CLOUDLEDGER TO ROLE CLOUDLEDGER_VIEWER;

-- Needed only so the project role can run its own scheduled refresh task.
GRANT EXECUTE TASK ON ACCOUNT TO ROLE CLOUDLEDGER_ROLE;
