-- CloudLedger objects. Run as CLOUDLEDGER_ROLE after 01_admin.sql.
-- No billing data or credentials appear in this file.
USE ROLE CLOUDLEDGER_ROLE;
USE WAREHOUSE CLOUDLEDGER_WH;
CREATE SCHEMA IF NOT EXISTS CLOUDLEDGER.CLOUD_FINANCE_BI;
USE SCHEMA CLOUDLEDGER.CLOUD_FINANCE_BI;

-- Code only (loader package and Streamlit app). Billing payloads go to RAW_COST_EXPLORER.
CREATE STAGE IF NOT EXISTS CODE_STAGE DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'CloudLedger code: cloud_finance.zip and Streamlit app files';

-- Raw landing: every payload submitted to the loader, kept for audit and replay.
CREATE TABLE IF NOT EXISTS RAW_COST_EXPLORER (
  PAYLOAD_SHA256 VARCHAR NOT NULL,
  RECEIVED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  RECEIVED_BY VARCHAR DEFAULT CURRENT_USER(),
  PAYLOAD VARIANT NOT NULL);

-- Published snapshot and audit (same definitions the loader's setup() creates).
CREATE TABLE IF NOT EXISTS COST_DAILY (
  USAGE_DATE DATE NOT NULL, ACCOUNT_KEY VARCHAR NOT NULL, SERVICE VARCHAR NOT NULL,
  TEAM VARCHAR NOT NULL, UNBLENDED_COST NUMBER(28,10) NOT NULL,
  CURRENCY VARCHAR NOT NULL, ESTIMATED BOOLEAN NOT NULL, SOURCE_SNAPSHOT VARCHAR NOT NULL);
CREATE TABLE IF NOT EXISTS LOAD_AUDIT (
  SOURCE_SNAPSHOT VARCHAR, LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  ROW_COUNT NUMBER, SOURCE_TOTAL NUMBER(28,10), START_DATE DATE, END_DATE DATE);
CREATE TABLE IF NOT EXISTS LOAD_FAILURES (
  FAILED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PAYLOAD_SHA256 VARCHAR, ERROR_MESSAGE VARCHAR);

-- Reporting snapshots. A snapshot is registered in REPORT_SNAPSHOTS only when its
-- rows were written and reconciled in the same transaction, so CURRENT_* views
-- always show the last successful refresh.
CREATE TABLE IF NOT EXISTS REPORT_SNAPSHOTS (
  SNAPSHOT_ID VARCHAR NOT NULL, CREATED_AT TIMESTAMP_LTZ NOT NULL,
  SOURCE_SNAPSHOT VARCHAR NOT NULL, ROW_COUNT NUMBER NOT NULL,
  SOURCE_TOTAL NUMBER(28,10) NOT NULL, START_DATE DATE, END_DATE DATE);
CREATE TABLE IF NOT EXISTS REPORT_DAILY (
  SNAPSHOT_ID VARCHAR NOT NULL, USAGE_DATE DATE NOT NULL,
  ACTUAL_COST NUMBER(28,10) NOT NULL, HAS_ESTIMATES BOOLEAN NOT NULL);
CREATE TABLE IF NOT EXISTS REPORT_SERVICE_MONTH (
  SNAPSHOT_ID VARCHAR NOT NULL, USAGE_MONTH DATE NOT NULL, SERVICE VARCHAR NOT NULL,
  TEAM VARCHAR NOT NULL, CURRENCY VARCHAR NOT NULL,
  ACTUAL_COST NUMBER(28,10) NOT NULL, HAS_ESTIMATES BOOLEAN NOT NULL);
CREATE TABLE IF NOT EXISTS REFRESH_LOG (
  RUN_ID VARCHAR, STARTED_AT TIMESTAMP_LTZ, FINISHED_AT TIMESTAMP_LTZ,
  STATUS VARCHAR, TRIGGERED_BY VARCHAR, SNAPSHOT_ID VARCHAR, SOURCE_SNAPSHOT VARCHAR,
  ROW_COUNT NUMBER, SOURCE_TOTAL NUMBER(28,10), SOURCE_END DATE,
  SOURCE_LAG_DAYS NUMBER, FRESHNESS VARCHAR, ERROR_MESSAGE VARCHAR);

CREATE OR REPLACE VIEW DAILY_COST AS
  SELECT USAGE_DATE, SUM(UNBLENDED_COST) ACTUAL_COST, BOOLOR_AGG(ESTIMATED) HAS_ESTIMATES
  FROM COST_DAILY GROUP BY 1;
CREATE OR REPLACE VIEW MONTHLY_SERVICE_TEAM_COST AS
  SELECT DATE_TRUNC('MONTH', USAGE_DATE) USAGE_MONTH, SERVICE, TEAM, CURRENCY,
         SUM(UNBLENDED_COST) ACTUAL_COST, BOOLOR_AGG(ESTIMATED) HAS_ESTIMATES
  FROM COST_DAILY GROUP BY 1,2,3,4;
CREATE OR REPLACE VIEW CURRENT_SNAPSHOT AS
  SELECT * FROM REPORT_SNAPSHOTS QUALIFY ROW_NUMBER() OVER (ORDER BY CREATED_AT DESC) = 1;
CREATE OR REPLACE VIEW CURRENT_REPORT_DAILY AS
  SELECT d.USAGE_DATE, d.ACTUAL_COST, d.HAS_ESTIMATES
  FROM REPORT_DAILY d JOIN CURRENT_SNAPSHOT s ON d.SNAPSHOT_ID = s.SNAPSHOT_ID;
CREATE OR REPLACE VIEW CURRENT_REPORT_SERVICE_MONTH AS
  SELECT m.USAGE_MONTH, m.SERVICE, m.TEAM, m.CURRENCY, m.ACTUAL_COST, m.HAS_ESTIMATES
  FROM REPORT_SERVICE_MONTH m JOIN CURRENT_SNAPSHOT s ON m.SNAPSHOT_ID = s.SNAPSHOT_ID;
CREATE OR REPLACE VIEW FRESHNESS_STATUS AS
  SELECT
    (SELECT MAX(LOADED_AT) FROM LOAD_AUDIT) LAST_SUCCESSFUL_LOAD_AT,
    (SELECT MAX(FAILED_AT) FROM LOAD_FAILURES) LAST_LOAD_FAILURE_AT,
    s.SNAPSHOT_ID CURRENT_SNAPSHOT_ID, s.CREATED_AT CURRENT_SNAPSHOT_AT, s.END_DATE SOURCE_END,
    DATEDIFF('day', s.END_DATE, CURRENT_DATE()) SOURCE_LAG_DAYS,
    IFF(DATEDIFF('day', s.END_DATE, CURRENT_DATE()) <= 2, 'FRESH', 'STALE') FRESHNESS,
    (SELECT MAX(FINISHED_AT) FROM REFRESH_LOG WHERE STATUS = 'SUCCEEDED') LAST_SUCCESSFUL_REFRESH_AT,
    (SELECT MAX(FINISHED_AT) FROM REFRESH_LOG WHERE STATUS = 'FAILED') LAST_FAILED_REFRESH_AT
  FROM (SELECT 1 x) LEFT JOIN CURRENT_SNAPSHOT s ON TRUE;

-- AI-assisted analysis: recommendations carry their SQL evidence and stay
-- PENDING_REVIEW until a person records a decision. Decisions are append-only.
CREATE TABLE IF NOT EXISTS AI_RECOMMENDATIONS (
  REC_ID VARCHAR NOT NULL, CREATED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  RUN_ID VARCHAR NOT NULL, SNAPSHOT_ID VARCHAR NOT NULL, MODEL_ID VARCHAR NOT NULL,
  PROMPT_VERSION VARCHAR NOT NULL, RECOMMENDATION VARCHAR NOT NULL,
  EVIDENCE_IDS ARRAY, EVIDENCE VARIANT, EVALUATION VARIANT, PASSED_CHECKS BOOLEAN);
CREATE TABLE IF NOT EXISTS AI_REVIEW_EVENTS (
  REC_ID VARCHAR NOT NULL, DECISION VARCHAR NOT NULL, REVIEWER VARCHAR NOT NULL,
  NOTE VARCHAR, DECIDED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP());
CREATE OR REPLACE VIEW AI_RECOMMENDATION_STATUS AS
  SELECT r.*, COALESCE(e.DECISION, 'PENDING_REVIEW') REVIEW_STATUS, e.REVIEWER, e.NOTE, e.DECIDED_AT
  FROM AI_RECOMMENDATIONS r
  LEFT JOIN (SELECT * FROM AI_REVIEW_EVENTS
             QUALIFY ROW_NUMBER() OVER (PARTITION BY REC_ID ORDER BY DECIDED_AT DESC) = 1) e
    ON r.REC_ID = e.REC_ID;

-- Scheduled refresh: verify the published snapshot, build a new reporting snapshot
-- atomically, and log success or failure. A failure leaves the previous snapshot current.
CREATE OR REPLACE PROCEDURE REFRESH_REPORTING(FORCE_FAILURE BOOLEAN, TRIGGERED_BY VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS
$$
DECLARE
  run_id VARCHAR DEFAULT UUID_STRING();
  snap_id VARCHAR DEFAULT UUID_STRING();
  started TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP();
  n NUMBER DEFAULT 0;
  total NUMBER(28,10);
  snap_total NUMBER(28,10);
  src VARCHAR;
  s_start DATE;
  s_end DATE;
  a_rows NUMBER;
  a_total NUMBER(28,10);
  dups NUMBER;
  bad NUMBER;
  lag NUMBER;
  fresh VARCHAR;
  msg VARCHAR;
  empty_error EXCEPTION (-20101, 'No published billing snapshot in COST_DAILY');
  integrity_error EXCEPTION (-20102, 'COST_DAILY does not reconcile with its LOAD_AUDIT record');
  quality_error EXCEPTION (-20103, 'Duplicate grain or non-USD currency in COST_DAILY');
  forced_error EXCEPTION (-20104, 'Forced failure requested for verification');
  snapshot_error EXCEPTION (-20105, 'Reporting snapshot total does not equal source total');
BEGIN
  SELECT COUNT(*), SUM(UNBLENDED_COST), MIN(SOURCE_SNAPSHOT), MIN(USAGE_DATE), MAX(USAGE_DATE)
    INTO :n, :total, :src, :s_start, :s_end FROM COST_DAILY;
  IF (n = 0) THEN RAISE empty_error; END IF;
  SELECT ROW_COUNT, SOURCE_TOTAL INTO :a_rows, :a_total FROM LOAD_AUDIT
    WHERE SOURCE_SNAPSHOT = :src ORDER BY LOADED_AT DESC LIMIT 1;
  IF (a_rows IS NULL OR a_rows <> n OR a_total <> total) THEN RAISE integrity_error; END IF;
  SELECT COUNT(*) INTO :dups FROM
    (SELECT 1 FROM COST_DAILY GROUP BY USAGE_DATE, ACCOUNT_KEY, SERVICE HAVING COUNT(*) > 1);
  SELECT COUNT(*) INTO :bad FROM COST_DAILY WHERE CURRENCY <> 'USD';
  IF (dups > 0 OR bad > 0) THEN RAISE quality_error; END IF;
  lag := DATEDIFF('day', s_end, CURRENT_DATE());
  fresh := IFF(lag <= 2, 'FRESH', 'STALE');

  BEGIN TRANSACTION;
  INSERT INTO REPORT_DAILY
    SELECT :snap_id, USAGE_DATE, SUM(UNBLENDED_COST), BOOLOR_AGG(ESTIMATED) FROM COST_DAILY GROUP BY USAGE_DATE;
  INSERT INTO REPORT_SERVICE_MONTH
    SELECT :snap_id, DATE_TRUNC('MONTH', USAGE_DATE), SERVICE, TEAM, CURRENCY,
           SUM(UNBLENDED_COST), BOOLOR_AGG(ESTIMATED)
    FROM COST_DAILY GROUP BY 2, 3, 4, 5;
  IF (FORCE_FAILURE) THEN RAISE forced_error; END IF;
  SELECT SUM(ACTUAL_COST) INTO :snap_total FROM REPORT_DAILY WHERE SNAPSHOT_ID = :snap_id;
  IF (snap_total <> total) THEN RAISE snapshot_error; END IF;
  INSERT INTO REPORT_SNAPSHOTS
    VALUES (:snap_id, CURRENT_TIMESTAMP(), :src, :n, :total, :s_start, :s_end);
  COMMIT;

  INSERT INTO REFRESH_LOG VALUES (:run_id, :started, CURRENT_TIMESTAMP(), 'SUCCEEDED', :TRIGGERED_BY,
    :snap_id, :src, :n, :total, :s_end, :lag, :fresh, NULL);
  RETURN 'SUCCEEDED snapshot=' || snap_id || ' rows=' || n || ' total=' || total || ' freshness=' || fresh;
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    msg := SQLERRM;
    INSERT INTO REFRESH_LOG VALUES (:run_id, :started, CURRENT_TIMESTAMP(), 'FAILED', :TRIGGERED_BY,
      NULL, :src, :n, :total, :s_end, :lag, :fresh, :msg);
    RAISE;
END;
$$;

CREATE OR REPLACE TASK REFRESH_REPORTING_DAILY
  WAREHOUSE = CLOUDLEDGER_WH
  SCHEDULE = 'USING CRON 15 7 * * * America/New_York'
  COMMENT = 'Daily CloudLedger reporting refresh, integrity and freshness check'
AS CALL REFRESH_REPORTING(FALSE, 'task:REFRESH_REPORTING_DAILY');
ALTER TASK REFRESH_REPORTING_DAILY RESUME;

-- Read-only viewer access to reporting objects.
GRANT USAGE ON SCHEMA CLOUDLEDGER.CLOUD_FINANCE_BI TO ROLE CLOUDLEDGER_VIEWER;
GRANT SELECT ON VIEW CURRENT_REPORT_DAILY TO ROLE CLOUDLEDGER_VIEWER;
GRANT SELECT ON VIEW CURRENT_REPORT_SERVICE_MONTH TO ROLE CLOUDLEDGER_VIEWER;
GRANT SELECT ON VIEW FRESHNESS_STATUS TO ROLE CLOUDLEDGER_VIEWER;
